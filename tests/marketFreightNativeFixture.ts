import {createInitialWorld} from '../src/data/initialWorld';
import {availableMarketFreightActions} from '../src/engine/escortEngine';
import {marketClosureReason} from '../src/engine/marketEngine';
import {advanceWorldTick} from '../src/engine/worldEngine';
import type {LLMDecisionPayload,MarketGood,WorldState} from '../src/types/world';

export const freightSeller='npc-1',freightBuyer='npc-2',freightCarrier='npc-4',freightOther='npc-3';
export const freightOrigin='loc-market-east',freightDestination='loc-market';
export const freightActor=(world:WorldState,id:string)=>world.cultivators.find(row=>row.id===id)!;
export const freightContract=(world:WorldState)=>world.escorts.contracts.find(row=>row.freight!==undefined);
export const freightShipment=(world:WorldState)=>world.markets.shipments[0];
export function freightRequire(value:unknown,why:string):asserts value{if(!value)throw Error(why);}
export const freightDecision=(chosenAction:LLMDecisionPayload['chosenAction'],fields:Partial<LLMDecisionPayload>={}):LLMDecisionPayload=>
  ({chosenAction,...fields,innerMonologue:'照本单现货和亲自所见载重行事。'});
export function freightMonth(world:WorldState,commands:Readonly<Record<string,LLMDecisionPayload>>={}){
  return advanceWorldTick(world,Object.fromEntries(world.cultivators.filter(actor=>actor.alive&&actor.hp>0).map(({id})=>
    [id,commands[id]??freightDecision('REST')])),()=>.99,'utility',undefined,{captureTrace:false,capturePresentation:false});
}
export function nativeFreightShipment({good='jade_leaf',sellerQuantity=5,buyerQuantity=1}:{
  good?:Extract<MarketGood,'jade_leaf'|'earth_root'>;sellerQuantity?:number;buyerQuantity?:number
}={}){
  const start=createInitialWorld(5);
  // Disclosed controlled genesis only: initial actors at the two existing markets, visible starting stock
  // and carrier's provisions. Same genuine native seed, no clock, geography, order or shipment is edited.
  const seller=freightActor(start,freightSeller),buyer=freightActor(start,freightBuyer),guide=freightActor(start,freightCarrier);
  seller.locationId=guide.locationId=freightOrigin;buyer.locationId=freightDestination;
  freightActor(start,freightOther).locationId=freightOrigin;
  seller.herbs[good]=sellerQuantity;buyer.herbs[good]=0;
  guide.herbs.earth_root=4;guide.personality='逍遥';
  freightActor(start,freightOther).herbs.earth_root=4;
  let ready=start;
  for(let i=0;i<13;i++){
    if(!marketClosureReason({...ready,tick:ready.tick+1},freightDestination)&&
       !marketClosureReason({...ready,tick:ready.tick+1},freightOrigin))break;
    ready=freightMonth(ready);
  }
  const terms={marketGood:good,marketLimitPrice:11};
  const world=freightMonth(ready,{[freightSeller]:freightDecision('PLACE_MARKET_SELL',{...terms,marketQuantity:sellerQuantity}),
    [freightBuyer]:freightDecision('PLACE_MARKET_BUY',{...terms,marketQuantity:buyerQuantity})});
  const shipment=freightShipment(world);
  freightRequire(shipment?.status==='in_transit'&&shipment.sellerId===freightSeller&&shipment.buyerId===freightBuyer&&
    shipment.originId===freightOrigin&&shipment.destinationId===freightDestination&&shipment.quantity===Math.min(sellerQuantity,buyerQuantity),
  'Must use a physical cargo generated by exact real market match');
  return {start,world,shipment};
}
export function freightOpt(world:WorldState,id:string,move:NonNullable<LLMDecisionPayload['marketFreightMove']>){
  const option=availableMarketFreightActions(freightActor(world,id),world,world.tick+1).find(row=>
    row.marketFreightMove===move&&(row.marketFreightMove!=='offer'||row.targetCultivatorId===freightCarrier));
  freightRequire(option,`No actual ${move} by ${id} at T${world.tick}`);
  const {action,...fields}=option;
  return freightDecision(action,fields);
}
export function offeredNativeFreight(){
  const original=nativeFreightShipment();
  const world=freightMonth(original.world,{[freightSeller]:freightOpt(original.world,freightSeller,'offer')});
  const contract=freightContract(world);
  freightRequire(contract?.freight&&contract.status==='offered','Actual opt-in named freight offer');
  return {...original,matched:original.world,world,contract};
}
export function acceptedNativeFreight(){
  const offer=offeredNativeFreight();
  const world=freightMonth(offer.world,{[freightCarrier]:freightOpt(offer.world,freightCarrier,'accept')});
  const contract=freightContract(world);
  freightRequire(contract?.freight&&contract.status==='active','Actual named carrier accepted');
  return {...offer,offered:offer.world,world,contract};
}
