const UNKNOWN_ACTION = '行事中';
const PRIVATE_TRACE_ACTION = '未公开行动';

/** Display copy only: save, replay and provider commands retain their exact ActionType. */
export function labelAction(value: unknown): string {
  return typeof value === 'string' && Object.hasOwn(ACTION_LABELS, value)
    ? ACTION_LABELS[value as ActionType] : UNKNOWN_ACTION;
}

/** The trace uses short captions and has a deliberately narrower public action union. */
const TRACE_LABELS = {
  REST: '调息', CULTIVATE: '修炼', BREAKTHROUGH: '突破',
  SOCIALIZE: '交谈', EXPLORE: '探索', FACE_TRIBULATION: '迎战天劫',
} as const satisfies Record<PublicTraceAction, string>;

export function labelTraceAction(value: unknown): string {
  return typeof value === 'string' && Object.hasOwn(TRACE_LABELS, value)
    ? TRACE_LABELS[value as PublicTraceAction] : PRIVATE_TRACE_ACTION;
}

// Keep the existing nineteen-action public map/popover/dossier disclosure boundary.
const PUBLIC_MAP_ACTIONS: ReadonlySet<string> = new Set<ActionType>([
  'CULTIVATE','REST','BREAKTHROUGH','EXPLORE','DUEL','FACE_TRIBULATION',
  'SOCIALIZE','GATHER_HERBS','BREW_PILL','FORGE_ARTIFACT','STUDY_TECHNIQUE','AUTHOR_TECHNIQUE',
  'TEACH','DUAL_CULTIVATE','TRADE','PILGRIMAGE','GUARD_DUTY','TAME_BEAST',
  'DELIVER_RELIEF',
]);

export function labelPublicMapAction(value: unknown): string {
  return typeof value === 'string' && PUBLIC_MAP_ACTIONS.has(value) ? labelAction(value) : UNKNOWN_ACTION;
}
